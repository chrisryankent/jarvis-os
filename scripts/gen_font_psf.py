#!/usr/bin/env python3
"""
Generates kernel/font8x16.c from a PSF console font installed on the build
machine (default: Terminus 8x16 from the console-setup package).

Terminus Font is licensed under the SIL Open Font License 1.1, which permits
embedding and redistribution. The PSF unicode table is used to place each
glyph at its ASCII / Latin-1 code so font8x16[c] is the glyph for byte c.

usage: gen_font_psf.py [font.psf.gz] > kernel/font8x16.c
"""
import gzip, struct, sys

path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Lat15-Terminus16.psf.gz"
data = gzip.open(path, "rb").read() if path.endswith(".gz") else open(path, "rb").read()

glyphs, table = [], {}
if data[:2] == b"\x36\x04":                       # PSF1
    mode, height = data[2], data[3]
    count = 512 if mode & 1 else 256
    width, bpg, off = 8, height, 4
    for i in range(count):
        glyphs.append(data[off + i * bpg: off + (i + 1) * bpg])
    pos = off + count * bpg
    if mode & 6:
        for i in range(count):
            seq = False
            while pos + 1 < len(data):
                (u,) = struct.unpack_from("<H", data, pos); pos += 2
                if u == 0xFFFF: break
                if u == 0xFFFE: seq = True; continue
                if not seq: table.setdefault(u, i)
elif data[:4] == b"\x72\xb5\x4a\x86":             # PSF2
    _, _, hdr, flags, count, bpg, height, width = struct.unpack_from("<8I", data, 0)
    for i in range(count):
        glyphs.append(data[hdr + i * bpg: hdr + (i + 1) * bpg])
    pos = hdr + count * bpg
    if flags & 1:
        for i in range(count):
            end = data.index(b"\xff", pos)
            entry = data[pos:end].split(b"\xfe")[0]
            for ch in entry.decode("utf-8", errors="ignore"):
                table.setdefault(ord(ch), i)
            pos = end + 1
else:
    sys.exit("not a PSF font: " + path)

if width != 8 or height != 16:
    sys.exit("need an 8x16 font, got %dx%d" % (width, height))

print("/*")
print(" * kernel/font8x16.c - 8x16 bitmap font, generated by scripts/gen_font_psf.py")
print(" * from %s." % path.split("/")[-1])
print(" *")
print(" * Terminus Font, Copyright (c) Dimitar Toshkov Zhekov,")
print(" * licensed under the SIL Open Font License, Version 1.1.")
print(" *")
print(" * font8x16[c][row]: one byte per row, bit 7 = leftmost pixel.")
print(" */")
print()
print("#include <stdint.h>")
print()
print("const uint8_t font8x16[256][16] = {")
for c in range(256):
    g = glyphs[table[c]] if (32 <= c < 127 or c >= 160) and c in table else bytes(16)
    print("    {%s},  /* 0x%02x */" % (",".join("0x%02x" % b for b in g), c))
print("};")
