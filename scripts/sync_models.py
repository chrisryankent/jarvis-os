#!/usr/bin/env python3
"""Sync packaged models into the ISO tree and generate kernel model markers."""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path


MODEL_SUFFIXES = {
    ".gguf",
    ".bin",
    ".onnx",
    ".safetensors",
    ".pth",
    ".pt",
    ".ckpt",
    ".json",
    ".txt",
    ".yaml",
}

REQUIRED_MODEL_GROUPS = {
    "brain": ["brain/model.gguf"],
    "stt": ["stt/ggml-medium.en.bin", "stt/ggml-tiny.en.bin", "stt/ggml-large-v3.bin"],
    "tts": ["tts/kokoro-v1.0.onnx", "tts/kokoro-v1_0.pth"],
    "wake": ["wake/wake_word.onnx"],
}


def should_package(path: Path) -> bool:
    if path.name.startswith(".git"):
        return False
    if path.suffix.lower() in MODEL_SUFFIXES:
        return True
    return path.name in {"manifest.json", "README.md"}


def copy_if_changed(src: Path, dst: Path) -> bool:
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists():
        src_stat = src.stat()
        dst_stat = dst.stat()
        if src_stat.st_size == dst_stat.st_size and int(src_stat.st_mtime) <= int(dst_stat.st_mtime):
            return False
    shutil.copy2(src, dst)
    return True


def iter_model_files(models_dir: Path):
    if not models_dir.exists():
        return
    for path in sorted(models_dir.rglob("*")):
        if path.is_file() and should_package(path):
            yield path


def c_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"')


def generate_manifest(models_dir: Path, output: Path) -> tuple[int, int]:
    entries = []
    total_size = 0

    for path in iter_model_files(models_dir) or []:
        rel = path.relative_to(models_dir).as_posix()
        jarvis_path = f"/jarvis/models/{rel}"
        size = path.stat().st_size
        total_size += size
        entries.append((jarvis_path, size))

    lines = [
        "/* Auto-generated by scripts/sync_models.py. Do not edit by hand. */",
        '#include "kernel.h"',
        "",
        "typedef struct {",
        "    const char *path;",
        "    uint64_t size;",
        "} packaged_model_t;",
        "",
        "static const packaged_model_t packaged_models[] = {",
    ]

    for path, size in entries:
        lines.append(f'    {{ "{c_escape(path)}", {size}ULL }},')

    lines += [
        "};",
        "",
        "void vfs_seed_packaged_models(void)",
        "{",
        "    size_t count = sizeof(packaged_models) / sizeof(packaged_models[0]);",
        "    if (count == 0) {",
        '        terminal_puts("[VFS] No packaged model manifest entries\\n");',
        "        return;",
        "    }",
        "",
        "    for (size_t i = 0; i < count; i++) {",
        "        if (vfs_stat(packaged_models[i].path) != 0)",
        "            vfs_create_file(packaged_models[i].path);",
        "    }",
        "",
        '    terminal_printf("[VFS] Packaged model manifest: %zu file(s) visible\\n", count);',
        "}",
        "",
    ]

    content = "\n".join(lines)
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists() and output.read_text() == content:
        return len(entries), total_size
    output.write_text(content)
    return len(entries), total_size


def sync_iso(models_dir: Path, iso_models_dir: Path) -> tuple[int, int]:
    copied = 0
    total = 0
    for path in iter_model_files(models_dir) or []:
        rel = path.relative_to(models_dir)
        total += 1
        if copy_if_changed(path, iso_models_dir / rel):
            copied += 1
    return copied, total


def warn_missing_required(models_dir: Path) -> None:
    for name, choices in REQUIRED_MODEL_GROUPS.items():
        if any((models_dir / choice).exists() for choice in choices):
            continue
        formatted = ", ".join(choices)
        print(f"[MODELS] WARN missing {name}: expected one of {formatted}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Sync JARVIS model assets")
    parser.add_argument("--models-dir", default="tools/models")
    parser.add_argument("--iso-models-dir", default="iso/jarvis/models")
    parser.add_argument("--kernel-manifest", default="kernel/model_manifest.c")
    parser.add_argument("--no-iso-sync", action="store_true")
    args = parser.parse_args()

    models_dir = Path(args.models_dir)
    if not models_dir.exists():
        print(f"[MODELS] Source directory missing: {models_dir}")
        Path(args.kernel_manifest).parent.mkdir(parents=True, exist_ok=True)
        generate_manifest(models_dir, Path(args.kernel_manifest))
        return 0

    count, total_size = generate_manifest(models_dir, Path(args.kernel_manifest))
    print(f"[MODELS] Kernel manifest: {count} file(s), {total_size // (1024 * 1024)} MB")
    warn_missing_required(models_dir)

    if not args.no_iso_sync:
        copied, total = sync_iso(models_dir, Path(args.iso_models_dir))
        print(f"[MODELS] ISO sync: {copied} copied/updated, {total} checked")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
