#!/usr/bin/env python3
"""Rasterise the UI fonts into drivers/font_aa.c.

JARVIS OS has no font engine in the kernel, so the faces it uses are
rendered here, once, at the exact pixel sizes the desktop draws, and stored
as 8-bit coverage maps (anti-aliased). The generated file is committed, so
building the OS does not need these fonts or Pillow.

Fonts: Noto Sans and Noto Sans Mono (SIL Open Font License 1.1, which allows
embedding). Run:  python3 tools/gen_fonts.py
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

NOTO = Path("/usr/share/fonts/truetype/noto")
DEJAVU = Path("/usr/share/fonts/truetype/dejavu")
# Noto Sans has no arrows or check mark: those come from DejaVu Sans
# (Bitstream Vera licence, free to embed).
FALLBACK_CHARS = set("\u2713\u2190\u2192\u2191\u2193")
FALLBACK = {"NotoSans-Regular.ttf": "DejaVuSans.ttf", "NotoSans-SemiBold.ttf": "DejaVuSans-Bold.ttf",
            "NotoSans-Light.ttf": "DejaVuSans.ttf", "NotoSansMono-Regular.ttf": "DejaVuSansMono.ttf",
            "NotoSansMono-SemiBold.ttf": "DejaVuSansMono-Bold.ttf"}
OUT = Path(__file__).resolve().parent.parent / "drivers" / "font_aa.c"

# Printable ASCII plus a few symbols the UI uses (stored after '~').
EXTRA = ["•", "…", "°", "✓", "←", "→", "↑", "↓", "×", "©"]
CHARS = [chr(c) for c in range(32, 127)] + EXTRA

# id, file, pixel size, cell height (the 8x16 text cell scaled), fixed advance
FACES = [
    ("UI",       "NotoSans-Regular.ttf",     13, 16, None),
    ("UI_BOLD",  "NotoSans-SemiBold.ttf",    13, 16, None),
    ("MONO",     "NotoSansMono-Regular.ttf", 13, 16, 8),
    ("MONO_BOLD", "NotoSansMono-SemiBold.ttf", 13, 16, 8),
    ("TITLE",    "NotoSans-SemiBold.ttf",    22, 32, None),
    ("LARGE",    "NotoSans-Regular.ttf",     32, 48, None),
    ("DISPLAY",  "NotoSans-Light.ttf",       58, 64, None),
    ("SMALL",    "NotoSans-Regular.ttf",     11, 14, None),
]

GAMMA = 0.82   # < 1 thickens thin stems a little; linear blending looks too light


def render_face(fid, fname, size, cell, fixed_adv):
    main_font = ImageFont.truetype(str(NOTO / fname), size)
    fb_font = ImageFont.truetype(str(DEJAVU / FALLBACK[fname]), size) if (DEJAVU / FALLBACK[fname]).exists() else main_font
    font = main_font
    cap = font.getbbox("H", anchor="ls")
    cap_h = -cap[1]
    baseline = cell // 2 + (cap_h + 1) // 2           # caps centred in the cell
    glyphs, data = [], bytearray()
    for ch in CHARS:
        font = fb_font if ch in FALLBACK_CHARS else main_font
        adv = fixed_adv * 64 if fixed_adv else int(round(font.getlength(ch) * 64))
        box = font.getbbox(ch, anchor="ls")
        if ch == " " or box[2] <= box[0] or box[3] <= box[1]:
            glyphs.append((0, 0, 0, 0, adv, 0))
            continue
        pad = 4
        w, h = box[2] - box[0] + pad * 2, box[3] - box[1] + pad * 2
        img = Image.new("L", (w, h), 0)
        ox = pad - box[0]
        if fixed_adv:      # centre mono glyphs in their cell
            ox += int(round((fixed_adv - font.getlength(ch)) / 2))
        ImageDraw.Draw(img).text((ox, pad - box[1]), ch, font=font, fill=255, anchor="ls")
        bb = img.getbbox()
        if not bb:
            glyphs.append((0, 0, 0, 0, adv, 0))
            continue
        crop = img.crop(bb)
        gw, gh = crop.size
        bx = bb[0] - ox            # left bearing from the pen position
        by = bb[1] - (pad - box[1])  # top relative to the baseline (negative = above)
        off = len(data)
        for v in crop.getdata():
            data.append(min(255, int(round(255 * (v / 255) ** GAMMA))))
        glyphs.append((gw, gh, bx, by, adv, off))
    return dict(id=fid, size=size, cell=cell, baseline=baseline, glyphs=glyphs, data=data)


def main():
    faces = [render_face(*f) for f in FACES]
    out = ["/* Generated by tools/gen_fonts.py from Noto Sans / Noto Sans Mono",
           " * (SIL Open Font License 1.1). Do not edit by hand. */",
           "#include \"font_aa.h\"", ""]
    for f in faces:
        n = f["id"].lower()
        out.append(f"static const uint8_t g_{n}_alpha[{max(1, len(f['data']))}] = {{")
        d = f["data"]
        for i in range(0, len(d), 24):
            out.append("    " + ",".join(str(b) for b in d[i:i + 24]) + ",")
        if not d:
            out.append("    0,")
        out.append("};")
        out.append(f"static const font_glyph_t g_{n}_glyphs[FONT_GLYPHS] = {{")
        for g in f["glyphs"]:
            out.append("    {%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append("")
    out.append("const font_face_t g_font_faces[FONT_COUNT] = {")
    for f in faces:
        n = f["id"].lower()
        out.append(f"    [FONT_{f['id']}] = {{ {f['size']}, {f['cell']}, {f['baseline']}, g_{n}_glyphs, g_{n}_alpha }},")
    out.append("};")
    OUT.write_text("\n".join(out) + "\n")
    total = sum(len(f["data"]) for f in faces)
    print(f"wrote {OUT} ({len(faces)} faces, {total // 1024} KB of glyph data)")


if __name__ == "__main__":
    main()
