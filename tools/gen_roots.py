#!/usr/bin/env python3
"""Builds kernel/rootcerts.c: the root certificates JARVIS OS trusts for
HTTPS, taken from the Mozilla CA list as shipped in the host's
ca-certificates bundle. Run:  python3 tools/gen_roots.py [bundle.pem]"""
import base64, re, sys
from pathlib import Path

src = Path(sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/certs/ca-certificates.crt")
out = Path(__file__).resolve().parent.parent / "kernel" / "rootcerts.c"
pems = re.findall(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", src.read_text(), re.S)
ders = [base64.b64decode("".join(p.split())) for p in pems]
lines = ["/* Generated by tools/gen_roots.py from the Mozilla CA list (%s). %d roots. */" % (src.name, len(ders)),
         "#include <stdint.h>", ""]
for i, d in enumerate(ders):
    lines.append("static const uint8_t r%d[%d] = {" % (i, len(d)))
    for k in range(0, len(d), 24):
        lines.append("    " + ",".join(str(b) for b in d[k:k + 24]) + ",")
    lines.append("};")
lines.append("const uint8_t *const g_root_certs[] = { %s };" % ", ".join("r%d" % i for i in range(len(ders))))
lines.append("const uint32_t g_root_cert_len[] = { %s };" % ", ".join(str(len(d)) for d in ders))
lines.append("const int g_root_cert_count = %d;" % len(ders))
out.write_text("\n".join(lines) + "\n")
print("wrote %s: %d roots, %d KB" % (out, len(ders), sum(map(len, ders)) // 1024))
